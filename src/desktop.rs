//! medialib desktop app: the web UI in a native window.
//!
//! The window is a WebView (Edge WebView2 on Windows) pointed at the same
//! local server `medialib serve` runs, started in-process on a free port.
//! Reusing the web UI keeps one interface for both front ends, and WebView2
//! gives in-window video playback for free.

// No console window behind the app in release builds.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

use std::path::PathBuf;
use std::sync::mpsc;

use anyhow::{anyhow, Context, Result};
use tao::dpi::LogicalSize;
use tao::event::{Event, WindowEvent};
use tao::event_loop::{ControlFlow, EventLoop};
use tao::window::{Icon, Theme, WindowBuilder};
use wry::{WebContext, WebViewBuilder};

use medialib::config::Config;
use medialib::web::Server;

/// 64x64 RGBA, generated by assets/make_icon.py.
const ICON_RGBA: &[u8] = include_bytes!("../assets/icon-64.rgba");

fn main() {
    if let Err(e) = run() {
        // Release builds have no console, so errors need a dialog.
        rfd::MessageDialog::new()
            .set_level(rfd::MessageLevel::Error)
            .set_title("medialib")
            .set_description(format!("{e:#}"))
            .set_buttons(rfd::MessageButtons::Ok)
            .show();
        std::process::exit(1);
    }
}

/// Settings, index and WebView profile live in %APPDATA%\medialib, so the
/// app works the same wherever the executable is installed.
fn data_dir() -> PathBuf {
    std::env::var_os("APPDATA")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("XDG_CONFIG_HOME").map(PathBuf::from))
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
        .unwrap_or_else(|| PathBuf::from("."))
        .join("medialib")
}

fn run() -> Result<()> {
    let dir = data_dir();
    std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;

    // One instance at a time: two would each run a sync worker against the
    // same database. The OS drops the lock when the process exits, so a
    // crash can't leave it stuck.
    let lock = std::fs::OpenOptions::new()
        .create(true)
        .truncate(false)
        .write(true)
        .open(dir.join("app.lock"))?;
    if lock.try_lock().is_err() {
        rfd::MessageDialog::new()
            .set_level(rfd::MessageLevel::Info)
            .set_title("medialib")
            .set_description("medialib is already open. Look for it in the taskbar.")
            .set_buttons(rfd::MessageButtons::Ok)
            .show();
        return Ok(());
    }

    let config_path = dir.join("config.toml");
    let config = Config::load_or_create(&config_path)?;

    // The window's event loop must own the main thread, so the server gets
    // its own thread and runtime. Port 0 lets the OS pick a free port; the
    // bound address comes back over the channel before the window opens.
    let (tx, rx) = mpsc::channel::<Result<std::net::SocketAddr>>();
    std::thread::spawn(move || {
        let rt = match tokio::runtime::Builder::new_multi_thread().enable_all().build() {
            Ok(rt) => rt,
            Err(e) => {
                let _ = tx.send(Err(anyhow!(e)));
                return;
            }
        };
        rt.block_on(async move {
            match Server::bind(config, config_path, 0).await {
                Ok(server) => {
                    let _ = tx.send(server.addr());
                    if let Err(e) = server.run().await {
                        eprintln!("server stopped: {e:#}");
                    }
                }
                Err(e) => {
                    let _ = tx.send(Err(e));
                }
            }
        });
    });
    let addr = rx.recv().context("the app's server failed to start")??;
    let origin = format!("http://{addr}");

    let event_loop = EventLoop::new();
    let window = WindowBuilder::new()
        .with_title("medialib")
        .with_inner_size(LogicalSize::new(1180.0, 780.0))
        .with_min_inner_size(LogicalSize::new(720.0, 480.0))
        .with_window_icon(Icon::from_rgba(ICON_RGBA.to_vec(), 64, 64).ok())
        .with_theme(Some(Theme::Dark))
        .build(&event_loop)?;

    // WebView2 keeps a browser profile on disk. Its default spot is next to
    // the executable, which may not be writable, so keep it with our data.
    let mut context = WebContext::new(Some(dir.join("webview")));
    let allowed = origin.clone();
    let _webview = WebViewBuilder::new_with_web_context(&mut context)
        .with_url(format!("{origin}/"))
        .with_background_color((14, 16, 20, 255))
        .with_devtools(cfg!(debug_assertions))
        // The window only ever shows the app itself.
        .with_navigation_handler(move |url| url.starts_with(&allowed) || url == "about:blank")
        .build(&window)
        .context("opening the app window (is Microsoft Edge WebView2 installed?)")?;

    event_loop.run(move |event, _, control_flow| {
        *control_flow = ControlFlow::Wait;
        if let Event::WindowEvent {
            event: WindowEvent::CloseRequested,
            ..
        } = event
        {
            *control_flow = ControlFlow::Exit;
        }
    });
}
